const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const ts = require('typescript');
const { JSDOM } = require(path.join(require('node:os').tmpdir(), 'at02-react-dom-test/node_modules/jsdom'));
const before = process.argv.includes('--before');
const base = before ? '../../docs/acceptance/deployment/releases/985193fa8987e002/source' : './stage';
const dom = new JSDOM('<div id="app"></div>', { url: 'https://example.test' });
Object.assign(global, { window: dom.window, document: dom.window.document, localStorage: dom.window.localStorage, sessionStorage: dom.window.sessionStorage, IS_REACT_ACT_ENVIRONMENT: true });
const React = require('react');
const { createRoot } = require('react-dom/client');
for (const ext of ['.ts', '.tsx']) require.extensions[ext] = (module, file) => module._compile(ts.transpileModule(fs.readFileSync(file, 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, jsx: ts.JsxEmit.ReactJSX, target: ts.ScriptTarget.ES2022 } }).outputText, file);
const { AddRideModal } = require(base + '/src/components/AddRideModal.tsx');
const { ParentPortal } = require(base + '/src/components/ParentPortal.tsx');
const { ApiService } = require(base + '/src/services/api.ts');
(async () => {
  ApiService.enterDemo('parent');
  const students = await ApiService.getStudents(), initial = await ApiService.getRides();
  assert.equal(students[0].ticketBalance, 7);
  const root = createRoot(document.querySelector('#app'));
  let created;
  await React.act(() => root.render(React.createElement(AddRideModal, { isOpen: true, students, initialStudentId: students[0].id, onClose() {}, onSubmit: async data => { created = await ApiService.createReservation(data); } })));
  const radios = [...document.querySelectorAll('input[type=radio]')];
  assert.equal(radios.length, 3);
  const group = radios[0].closest('fieldset');
  const legend = group?.querySelector(':scope > legend')?.textContent ?? null;
  const allGrouped = !!group && radios.every(el => el.closest('fieldset') === group);
  const focusStyle = radios.every(el => el.parentElement.classList.contains('focus-within:ring-2'));
  assert.equal(allGrouped, !before);
  assert.equal(focusStyle, !before);
  if (!before) assert.match(legend, /送迎区分/);
  const choice = radios.find(el => el.value === 'roundtrip');
  await React.act(() => choice.click());
  assert.equal(choice.checked, true);
  await React.act(() => document.querySelector('form').requestSubmit());
  assert.equal(created.rideType, 'roundtrip');
  assert.equal(created.reservedBy, 'parent');
  const rides = await ApiService.getRides(), after = await ApiService.getStudents();
  assert.deepEqual(after, students);
  assert.equal(rides.length, initial.length + 1);
  assert.equal(rides.filter(r => r.id === created.id).length, 1);
  assert.deepEqual(rides.filter(r => r.id !== created.id), initial);
  await React.act(() => root.render(React.createElement(ParentPortal, { isDemo: true, students: after, rides, onOpenAddRide() {}, onCancelRide() {} })));
  assert.ok([...document.querySelectorAll('button')].some(el => el.getAttribute('aria-label')?.includes([created.rideDate, created.rideTime, '往復送迎'].join(' '))));
  const result = { case: 'AT-08', checkedAt: new Date().toISOString(), scope: 'synthetic parent demo / React form -> ApiService -> fresh parent list', legend, allGrouped, focusStyle, totalRidesBefore: initial.length, totalRidesAfter: rides.length, preservedOtherRides: true, reservedBy: created.reservedBy, rideType: created.rideType, displayedInList: true, balanceBefore: 7, balanceAfter: after[0].ticketBalance };
  fs.writeFileSync(path.join(__dirname, before ? 'before.json' : 'at08.json'), JSON.stringify(result, null, 2));
  console.log(result);
  await React.act(() => root.unmount());
})().catch(error => { console.error(error); process.exitCode = 1; });
