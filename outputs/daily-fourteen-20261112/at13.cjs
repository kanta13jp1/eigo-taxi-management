const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const ts = require('typescript');
const { JSDOM } = require(path.join(require('node:os').tmpdir(), 'at02-react-dom-test/node_modules/jsdom'));
const before = process.argv.includes('--before');
const base = before ? '../../docs/acceptance/deployment/releases/b88aec3501218a21/source' : './stage';
const dom = new JSDOM('<div id="app"></div>', { url: 'https://example.test' });
Object.assign(global, { window: dom.window, document: dom.window.document, localStorage: dom.window.localStorage, sessionStorage: dom.window.sessionStorage, IS_REACT_ACT_ENVIRONMENT: true });
const React = require('react');
const { createRoot } = require('react-dom/client');
for (const ext of ['.ts', '.tsx']) require.extensions[ext] = (module, file) => module._compile(ts.transpileModule(fs.readFileSync(file, 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, jsx: ts.JsxEmit.ReactJSX, target: ts.ScriptTarget.ES2022 } }).outputText, file);
const { TeacherDashboard } = require(base + '/src/components/TeacherDashboard.tsx');
const { ApiService, getLocalDateString } = require(base + '/src/services/api.ts');
(async () => {
  ApiService.enterDemo('admin');
  const students = await ApiService.getStudents();
  const first = students[0], today = getLocalDateString();
  assert.equal(first.ticketBalance, 7);
  const target = await ApiService.createReservation({ studentId: first.id, rideDate: today, rideTime: '16:30', rideType: 'pickup', pickupLocation: '確認用停留所', reservedBy: 'teacher' });
  const second = await ApiService.createReservation({ studentId: students[1].id, rideDate: today, rideTime: '16:30', rideType: 'roundtrip', pickupLocation: '別の停留所', reservedBy: 'teacher' });
  const initialRides = await ApiService.getRides();
  let handled = null, completion;
  const root = createRoot(document.querySelector('#app'));
  const render = async () => {
    const props = { isDemo: true, students: await ApiService.getStudents(), rides: await ApiService.getRides(), onCompleteRide: async id => { handled = id; completion = await ApiService.completeRide(id); } };
    await React.act(() => root.render(React.createElement(TeacherDashboard, props)));
  };
  const buttons = () => [...document.querySelectorAll('button')];
  const name = r => '送迎完了（' + (r.rideType === 'roundtrip' ? 2 : 1) + '回消費） ' + r.studentName + ' ' + r.rideDate + ' ' + r.rideTime + ' ' + (r.rideType === 'roundtrip' ? '往復' : 'お迎え');
  const named = r => buttons().find(b => b.getAttribute('aria-label') === name(r));
  await render();
  assert.equal(!!named(target), !before);
  assert.equal(!!named(second), !before);
  await React.act(() => buttons().find(b => b.textContent.includes('送迎スケジュール一覧')).click());
  assert.equal(!!named(target), !before);
  assert.equal(!!named(second), !before);
  const result = { case: 'AT-13', checkedAt: new Date().toISOString(), scope: 'local synthetic admin React and ApiService', bothListsExposeRideSpecificNames: !before };
  if (!before) {
    await React.act(() => named(target).click());
    assert.equal(handled, target.id);
    assert.equal(completion.consumedTickets, 1);
    const updated = await ApiService.getRides(), after = await ApiService.getStudents();
    const completed = updated.find(r => r.id === target.id);
    assert.equal(completed.status, 'completed');
    assert.ok(completed.completedAt);
    assert.deepEqual(updated.filter(r => r.id !== target.id), initialRides.filter(r => r.id !== target.id));
    assert.equal(after[0].ticketBalance, 6);
    assert.deepEqual(after.slice(1), students.slice(1));
    await render();
    assert.equal(!!named(target), false);
    assert.ok(named(second));
    assert.ok(document.body.textContent.includes('完了済 (-1回)'));
    Object.assign(result, { completedAt: completed.completedAt, status: completed.status, balanceBefore: 7, balanceAfter: 6, otherRidesAndBalancesPreserved: true, targetIdMatched: true });
  }
  await React.act(() => root.unmount());
  fs.writeFileSync(path.join(__dirname, before ? 'before.json' : 'at13.json'), JSON.stringify(result, null, 2));
  console.log(result);
})().catch(e => { console.error(e); process.exitCode = 1; });
