const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const ts = require('typescript');
const { JSDOM } = require(path.join(require('node:os').tmpdir(), 'at02-react-dom-test/node_modules/jsdom'));
const before = process.argv.includes('--before');
const base = before ? '../../docs/acceptance/deployment/releases/47d533a917506138/source' : './stage';
const dom = new JSDOM('<div id="app"></div>', { url: 'https://example.test' });
Object.assign(global, { window: dom.window, document: dom.window.document, localStorage: dom.window.localStorage, sessionStorage: dom.window.sessionStorage, IS_REACT_ACT_ENVIRONMENT: true });
const React = require('react');
const { createRoot } = require('react-dom/client');
for (const ext of ['.ts', '.tsx']) require.extensions[ext] = (module, file) => module._compile(ts.transpileModule(fs.readFileSync(file, 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, jsx: ts.JsxEmit.ReactJSX, target: ts.ScriptTarget.ES2022 } }).outputText, file);
const { ParentPortal } = require(base + '/src/components/ParentPortal.tsx');
const { ApiService } = require(base + '/src/services/api.ts');
(async () => {
  ApiService.enterDemo('parent');
  const students = await ApiService.getStudents();
  assert.deepEqual(students.map(s => s.id), ['STU-001']);
  const first = students[0];
  assert.equal(first.ticketBalance, 7);
  const second = { ...first, id: 'fixture-sibling', name: '確認用きょうだい', ticketBalance: 4 };
  const rides = [first, second].map(s => ({ id: s.id, studentId: s.id, rideDate: '2026-11-12', rideTime: '16:00', rideType: 'pickup', status: 'scheduled', pickupLocation: s.id + 'の乗車場所' }));
  const root = createRoot(document.querySelector('#app'));
  let requested;
  const render = rows => React.act(() => root.render(React.createElement(ParentPortal, { isDemo: true, students: rows, rides, onOpenAddRide(id) { requested = id; }, onCancelRide() {} })));
  const body = () => document.body.textContent;
  const checkCard = (shown, other) => {
    assert.equal(document.querySelector('select').value, shown.id);
    assert.equal(document.querySelector('h3').textContent, shown.name + ' さん');
    assert.ok(body().includes(shown.ticketBalance + '回分'));
    assert.ok(body().includes('片道1回につきチケット1枚'));
    assert.ok(body().includes(shown.id + 'の乗車場所'));
    assert.ok(!body().includes(other.id + 'の乗車場所'));
    [...document.querySelectorAll('button')].find(b => b.textContent.includes('予約を申し込む')).click();
    assert.equal(requested, shown.id);
  };
  await render([]);
  await render(students);
  const labelled = document.querySelector('select').labels.length === 1;
  const cardAfterLoading = !!document.querySelector('h3');
  assert.equal(labelled, !before);
  assert.equal(cardAfterLoading, !before);
  await render([first, second]);
  const select = document.querySelector('select');
  await React.act(() => { select.value = second.id; select.dispatchEvent(new window.Event('change', { bubbles: true })); });
  checkCard(second, first);
  await render([first]);
  const cardAfterRemoval = !!document.querySelector('h3');
  assert.equal(cardAfterRemoval, !before);
  if (!before) checkCard(first, second);
  await render([]);
  assert.ok(body().includes('登録されている生徒がいません'));
  assert.equal(document.querySelector('select'), null);
  await React.act(() => root.unmount());
  const result = { case: 'AT-03', checkedAt: new Date().toISOString(), scope: 'local parent demo API and synthetic React refresh/sibling fixtures', allowedDemoOptions: students.length, ownBalance: first.ticketBalance, labelled, cardAfterLoading, switchedSiblingBalance: second.ticketBalance, cardAfterRemoval, emptyState: true };
  fs.writeFileSync(path.join(__dirname, before ? 'before.json' : 'at03.json'), JSON.stringify(result, null, 2));
  console.log(result);
})().catch(e => { console.error(e); process.exitCode = 1; });
