const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const ts = require('typescript');
const { JSDOM } = require(path.join(require('node:os').tmpdir(), 'at02-react-dom-test/node_modules/jsdom'));
const before = process.argv.includes('--before');
const base = before ? '../../docs/acceptance/deployment/releases/6755531e1441c5d6/source' : './stage';
const dom = new JSDOM('<div id="app"></div>', { url: 'https://example.test/#/admin' });
Object.assign(global, { window: dom.window, document: dom.window.document, localStorage: dom.window.localStorage, sessionStorage: dom.window.sessionStorage, IS_REACT_ACT_ENVIRONMENT: true });
const React = require('react');
const { createRoot } = require('react-dom/client');
for (const ext of ['.ts', '.tsx']) require.extensions[ext] = (module, file) => module._compile(ts.transpileModule(fs.readFileSync(file, 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, jsx: ts.JsxEmit.ReactJSX, target: ts.ScriptTarget.ES2022 } }).outputText, file);
const { App } = require(base + '/src/App.tsx');
const { ApiService, getLocalDateString } = require(base + '/src/services/api.ts');
(async () => {
  ApiService.enterDemo('admin');
  const students = await ApiService.getStudents();
  const first = students.find(s => s.ticketBalance === 7);
  const second = students.find(s => s.id !== first.id);
  const create = (student, time) => ApiService.createReservation({ studentId: student.id, rideDate: getLocalDateString(), rideTime: time, rideType: 'pickup', pickupLocation: 'AT-15 fixture', reservedBy: 'teacher' });
  const target = await create(first, '15:37'), other = await create(second, '15:38');
  const initial = await ApiService.getRides();
  const original = ApiService.completeRide.bind(ApiService);
  const pending = new Map(), calls = [];
  for (const id of [target.id, other.id]) pending.set(id, Promise.withResolvers());
  ApiService.completeRide = async id => { calls.push(id); return pending.get(id).promise; };
  const root = createRoot(document.querySelector('#app'));
  const buttons = () => [...document.querySelectorAll('button')];
  const button = r => buttons().find(b => b.getAttribute('aria-label')?.endsWith(r.studentName + ' ' + r.rideDate + ' ' + r.rideTime + ' お迎え'));
  await React.act(async () => root.render(React.createElement(App)));
  await React.act(async () => { const b = button(target); b.click(); b.click(); });
  assert.equal(calls.length, before ? 2 : 1);
  assert.equal(button(target).disabled, !before);
  assert.equal(button(target).textContent.includes('完了処理中'), !before);
  await React.act(async () => buttons().find(b => b.textContent.includes('送迎スケジュール一覧')).click());
  assert.equal(button(target).disabled, !before);
  assert.equal(button(target).textContent.includes('完了処理中'), !before);
  assert.equal(button(other).disabled, false);
  await React.act(async () => button(other).click());
  assert.equal(calls.at(-1), other.id);
  await React.act(async () => pending.get(other.id).reject(new Error('別予約の模擬失敗')));
  assert.equal(button(target).disabled, !before);
  assert.equal(button(other).disabled, false);
  await React.act(async () => pending.get(target.id).reject(new Error('対象の模擬失敗')));
  assert.equal(button(target).disabled, false);
  assert.match(document.querySelector('[role=alert]').textContent, /対象の模擬失敗/);
  assert.deepEqual(await ApiService.getStudents(), students);
  assert.deepEqual(await ApiService.getRides(), initial);
  const result = { case: 'AT-15', checkedAt: new Date().toISOString(), scope: 'React App with controlled pending promises; anonymous demo ApiService idempotency', duplicateSubmissionsBeforeResolution: calls.filter(id => id === target.id).length, bothListsDisabledWhilePending: !before, unrelatedRideEnabled: true, failedAttemptUnlocked: true };
  ApiService.completeRide = original;
  if (!before) {
    await React.act(async () => button(target).click());
    const once = await ApiService.getRides();
    const done = once.find(r => r.id === target.id);
    assert.equal(done.status, 'completed');
    assert.ok(done.completedAt);
    assert.equal((await ApiService.getStudentById(first.id)).ticketBalance, 6);
    assert.deepEqual(once.filter(r => r.id !== target.id), initial.filter(r => r.id !== target.id));
    assert.equal(button(target), undefined);
    const replay = await original(target.id);
    assert.equal(replay.consumedTickets, 0);
    assert.equal(replay.remainingBalance, 6);
    assert.deepEqual(await ApiService.getRides(), once);
    assert.deepEqual((await ApiService.getStudents()).filter(s => s.id !== first.id), students.filter(s => s.id !== first.id));
    Object.assign(result, { beforeBalance: 7, firstConsumed: 1, repeatConsumed: 0, afterBalance: 6, status: done.status, completedAtUnchanged: true, otherDataPreserved: true });
  }
  await React.act(async () => root.unmount());
  fs.writeFileSync(path.join(__dirname, before ? 'before.json' : 'at15.json'), JSON.stringify(result, null, 2));
  console.log(result);
})().catch(e => { console.error(e); process.exit(1); });
