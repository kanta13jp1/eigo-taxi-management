const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const ts = require('typescript');
const { JSDOM } = require(path.join(require('node:os').tmpdir(), 'at02-react-dom-test/node_modules/jsdom'));
const before = process.argv.includes('--before');
const base = before ? '../../docs/acceptance/deployment/releases/b10cd21819d6c229/source' : './stage';
const dom = new JSDOM('<div id="app"></div>', { url: 'https://example.test/#/admin' });
Object.assign(global, { window: dom.window, document: dom.window.document, localStorage: dom.window.localStorage, sessionStorage: dom.window.sessionStorage, IS_REACT_ACT_ENVIRONMENT: true });
const React = require('react');
const { createRoot } = require('react-dom/client');
for (const ext of ['.ts', '.tsx']) require.extensions[ext] = (module, file) => module._compile(ts.transpileModule(fs.readFileSync(file, 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, jsx: ts.JsxEmit.ReactJSX, target: ts.ScriptTarget.ES2022 } }).outputText, file);
const { App } = require(base + '/src/App.tsx');
const { ApiService, getLocalDateString } = require(base + '/src/services/api.ts');
// jsdom lacks the native dialog methods. The deployed Chrome UI checks modal behavior.
window.HTMLDialogElement.prototype.showModal = function () { this.open = true; };
window.HTMLDialogElement.prototype.close = function () { this.open = false; };
(async () => {
  ApiService.enterDemo('admin');
  const students = await ApiService.getStudents();
  const student = students[0], date = getLocalDateString();
  const target = await ApiService.createReservation({ studentId: student.id, rideDate: date, rideTime: '14:37', pickupLocation: 'AT-11 対象', rideType: 'dropoff', reservedBy: 'teacher' });
  const other = await ApiService.createReservation({ studentId: student.id, rideDate: date, rideTime: '15:38', pickupLocation: 'AT-11 別の予約', rideType: 'pickup', reservedBy: 'teacher' });
  const initial = await ApiService.getRides();
  const root = createRoot(document.querySelector('#app'));
  const click = async el => React.act(async () => el.click());
  const button = (scope, name) => [...scope.querySelectorAll('button')].find(b => b.textContent.includes(name));
  const row = () => [...document.querySelectorAll('tbody tr')].find(tr => tr.textContent.includes(target.pickupLocation));
  let calls = [];
  const cancel = ApiService.cancelReservation.bind(ApiService);
  ApiService.cancelReservation = async id => { calls.push(id); return cancel(id); };
  let prompt;
  window.confirm = message => { prompt = message; return false; };
  await React.act(async () => root.render(React.createElement(App)));
  await click(button(document, '送迎スケジュール一覧'));
  await click(button(row(), '取消'));
  let dialog = document.querySelector('dialog[open]');
  const targetDetails = [student.name, date, target.rideTime, '送り'];
  const result = { case: 'AT-11', checkedAt: new Date().toISOString(), scope: 'React App + anonymous demo ApiService; jsdom substitutes native dialog plumbing', confirmationIdentifiesTarget: !before };
  if (before) {
    assert.equal(dialog, null);
    assert.ok(prompt);
    assert.ok(targetDetails.every(detail => !prompt.includes(detail)));
  } else {
    assert.ok(dialog);
    assert.ok(targetDetails.every(detail => dialog.textContent.includes(detail)));
    assert.ok(dialog.textContent.includes('このブラウザ内'));
    assert.equal(dialog.querySelector('button').textContent, '戻る');
    await click(button(dialog, '戻る'));
    assert.equal(document.querySelector('dialog'), null);
    assert.deepEqual(calls, []);
    assert.deepEqual(await ApiService.getRides(), initial);
    assert.deepEqual(await ApiService.getStudents(), students);
    await click(button(row(), '取消'));
    await React.act(async () => document.querySelector('dialog').dispatchEvent(new window.Event('cancel', { bubbles: true })));
    assert.equal(document.querySelector('dialog'), null);
    assert.deepEqual(calls, []);
    await click(button(row(), '取消'));
    await click(button(document.querySelector('dialog'), '取消を確定'));
    assert.deepEqual(calls, [target.id]);
    const updated = await ApiService.getRides();
    assert.equal(updated.find(r => r.id === target.id).status, 'cancelled');
    assert.equal(updated.find(r => r.id === other.id).status, 'scheduled');
    assert.deepEqual(updated.filter(r => r.id !== target.id), initial.filter(r => r.id !== target.id));
    assert.deepEqual(await ApiService.getStudents(), students);
    assert.ok(row().textContent.includes('取消'));
    assert.equal(row().querySelectorAll('button').length, 0);
    Object.assign(result, { dismissAndEscapePreserved: true, cancelledExactlyTarget: true, otherReservationPreserved: true, balanceBefore: student.ticketBalance, balanceAfter: (await ApiService.getStudentById(student.id)).ticketBalance });
  }
  await React.act(async () => root.unmount());
  fs.writeFileSync(path.join(__dirname, before ? 'before.json' : 'at11.json'), JSON.stringify(result, null, 2));
  console.log(result);
})().catch(e => { console.error(e); process.exit(1); });
