const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const ts = require('typescript');
const { JSDOM } = require(path.join(require('node:os').tmpdir(), 'at02-react-dom-test/node_modules/jsdom'));
const before = process.argv.includes('--before');
const base = before ? '../../docs/acceptance/deployment/releases/383ff85ce1a54688/source' : './stage';
const dom = new JSDOM('<div id="app"></div>', { url: 'https://example.test/#/admin' });
Object.assign(global, { window: dom.window, document: dom.window.document, localStorage: dom.window.localStorage, sessionStorage: dom.window.sessionStorage, IS_REACT_ACT_ENVIRONMENT: true });
const React = require('react');
const { createRoot } = require('react-dom/client');
for (const ext of ['.ts', '.tsx']) require.extensions[ext] = (module, file) => module._compile(ts.transpileModule(fs.readFileSync(file, 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, jsx: ts.JsxEmit.ReactJSX, target: ts.ScriptTarget.ES2022 } }).outputText, file);
const { App } = require(base + '/src/App.tsx');
const { ApiService, getLocalDateString } = require(base + '/src/services/api.ts');
(async () => {
  ApiService.enterDemo('admin');
  const initialStudents = await ApiService.getStudents();
  const fixture = initialStudents.find(s => s.ticketBalance === 1);
  const ride = await ApiService.createReservation({ studentId: fixture.id, rideDate: getLocalDateString(), rideTime: '16:00', rideType: 'roundtrip', pickupLocation: 'AT-14 確認用', reservedBy: 'teacher' });
  const initialRides = await ApiService.getRides();
  const root = createRoot(document.querySelector('#app'));
  const buttons = () => [...document.querySelectorAll('button')];
  const find = text => buttons().find(b => b.textContent.trim() === text);
  const complete = () => buttons().find(b => b.getAttribute('aria-label')?.includes(ride.studentName + ' ' + ride.rideDate + ' ' + ride.rideTime + ' 往復'));
  const alert = () => document.querySelector('[role=alert]')?.textContent;
  await React.act(async () => root.render(React.createElement(App)));
  await React.act(async () => complete().click());
  assert.match(alert(), /不足/);
  assert.equal(!!find('台帳を再取得する'), before);
  assert.equal(!!find('チケット追加'), !before);
  assert.deepEqual(await ApiService.getStudents(), initialStudents);
  assert.deepEqual(await ApiService.getRides(), initialRides);
  const result = { case: 'AT-14', checkedAt: new Date().toISOString(), scope: 'React App + anonymous demo service in jsdom', insufficientBalance: 1, insufficientStatePreserved: true, dashboardAndTopUpVisible: !before, globalRetryShown: before };
  if (!before) {
    const originalComplete = ApiService.completeRide;
    ApiService.completeRide = async () => { throw new Error('模擬通信失敗'); };
    await React.act(async () => complete().click());
    assert.match(alert(), /模擬通信失敗/);
    assert.ok(find('チケット追加'));
    ApiService.completeRide = originalComplete;
    await React.act(async () => find('チケット追加').click());
    const form = document.querySelector('form');
    const select = form.querySelector('select');
    await React.act(async () => { select.value = fixture.id; select.dispatchEvent(new window.Event('change', { bubbles: true })); });
    const count = form.querySelector('input[type=number]');
    await React.act(async () => { Object.getOwnPropertyDescriptor(window.HTMLInputElement.prototype, 'value').set.call(count, '6'); count.dispatchEvent(new window.Event('input', { bubbles: true })); });
    await React.act(async () => form.requestSubmit());
    assert.equal((await ApiService.getStudentById(fixture.id)).ticketBalance, 7);
    await React.act(async () => complete().click());
    assert.equal(alert(), undefined);
    const rides = await ApiService.getRides(), students = await ApiService.getStudents();
    const completed = rides.find(r => r.id === ride.id);
    assert.equal(completed.status, 'completed');
    assert.ok(completed.completedAt);
    assert.equal(students.find(s => s.id === fixture.id).ticketBalance, 5);
    assert.deepEqual(students.filter(s => s.id !== fixture.id), initialStudents.filter(s => s.id !== fixture.id));
    assert.deepEqual(rides.filter(r => r.id !== ride.id), initialRides.filter(r => r.id !== ride.id));
    Object.assign(result, { balanceBeforeCompletion: 7, balanceAfterCompletion: 5, status: completed.status, completedAt: completed.completedAt, otherDataPreserved: true, simulatedMutationRejectionInline: true });
    await React.act(async () => root.render(null));
    const originalStudents = ApiService.getStudents;
    ApiService.getStudents = async () => { throw new Error('模擬台帳読込失敗'); };
    await React.act(async () => root.render(React.createElement(App)));
    assert.match(alert(), /模擬台帳読込失敗/);
    assert.ok(find('台帳を再取得する'));
    ApiService.getStudents = originalStudents;
    result.fatalLoadStillRequiresRetry = true;
  }
  await React.act(async () => root.unmount());
  fs.writeFileSync(path.join(__dirname, before ? 'before.json' : 'at14.json'), JSON.stringify(result, null, 2));
  console.log(result);
})().catch(e => { console.error(e); process.exit(1); });
